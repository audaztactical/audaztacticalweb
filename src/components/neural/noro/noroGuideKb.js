/**
 * @param {string} pathname
 */
export function kbForPath(pathname) {
  const path = String(pathname || '').replace(/\/$/, '') || '/'
  const hits = NORO_KB.filter((e) => (e.pagePaths || []).some((p) => path === p || path.startsWith(p + '/')))
  if (hits.length) return hits[0]
  // route prefix match
  const byRoute = NORO_KB.find((e) => {
    const r = e.route.split('?')[0]
    return r !== '/' && (path === r || path.startsWith(r))
  })
  return byRoute || null
}
